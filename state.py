"""
State definitions for the Multi-Agent Software Development Engine.

Defines all TypedDict-based state objects used for communication
between agents in the LangGraph workflow, ensuring type-safe
inter-agent messaging.
"""

from typing import TypedDict, List, Optional, Any, Dict, Annotated
from operator import add


# ── Task & Artifact Sub-types ───────────────────────────────────────────

class TaskItem(TypedDict):
    """A single atomic task in the project plan."""
    id: str
    title: str
    description: str
    status: str           # pending | in_progress | completed | failed
    assignee: str         # developer | architect | analyst
    priority: str         # high | medium | low
    output_file: str      # expected output filename


class CodeArtifact(TypedDict):
    """A code file generated by the Developer agent."""
    filename: str
    content: str
    language: str
    task_id: str
    version: int          # incremented on rework


class ReviewResult(TypedDict):
    """Quality review output from the Reviewer agent."""
    artifact_name: str
    score: int            # 0-100
    issues: List[str]
    suggestions: List[str]
    passed: bool
    review_summary: str


class ArchitectureDesign(TypedDict):
    """Architecture design output."""
    overview: str
    components: List[Dict[str, Any]]   # [{name, responsibility, interface, dependencies}]
    data_flow: str
    tech_stack: Dict[str, str]
    directory_structure: str
    design_rationale: str


class RequirementAnalysis(TypedDict):
    """Analysis output from Analyst agent."""
    summary: str
    functional_requirements: List[str]
    non_functional_requirements: List[str]
    scope_boundaries: List[str]
    clarification_questions: List[str]
    complexity_assessment: str        # low | medium | high


# ── Main Team State ─────────────────────────────────────────────────────

class TeamState(TypedDict):
    """
    The central state object flowing through the LangGraph workflow.
    Every agent reads/writes to this shared, typed state.
    """
    # ── Conversation ──
    messages: Annotated[List[Any], add]  # Full message history (accumulated)

    # ── Input ──
    requirement: str                     # Original user requirement

    # ── Analysis Phase ──
    analysis: Optional[Dict[str, Any]]   # RequirementAnalysis result

    # ── Architecture Phase ──
    architecture: Optional[Dict[str, Any]]  # ArchitectureDesign result
    task_plan: Optional[List[Dict[str, Any]]]  # List of TaskItem

    # ── Execution Phase ──
    current_task_index: int              # Index into task_plan
    code_artifacts: Optional[List[Dict[str, Any]]]  # List of CodeArtifact
    review_results: Optional[List[Dict[str, Any]]]  # List of ReviewResult

    # ── Control ──
    phase: str                           # init | analysis | architecture
                                         #   | development | review | synthesis | done
    next_agent: str                      # Routing target for conditional edges
    iteration: int                       # Current review-fix iteration
    max_iterations: int                  # Max review-fix iterations per task
    quality_threshold: int               # Minimum review score to pass (0-100)

    # ── Output ──
    final_output: str                    # Synthesized final deliverable
    execution_log: Annotated[List[str], add]  # Execution trace (accumulated)


# ── Default Factory ─────────────────────────────────────────────────────

def create_initial_state(requirement: str) -> TeamState:
    """Create a clean initial state for a new requirement."""
    return TeamState(
        messages=[],
        requirement=requirement,
        analysis=None,
        architecture=None,
        task_plan=None,
        current_task_index=0,
        code_artifacts=[],
        review_results=[],
        phase="init",
        next_agent="",
        iteration=0,
        max_iterations=3,
        quality_threshold=70,
        final_output="",
        execution_log=[],
    )
